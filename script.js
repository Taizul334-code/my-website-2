const langToggle = document.getElementById("langToggle");
const menuBtn = document.getElementById("menuBtn");
const navMenu = document.getElementById("navMenu");
const serviceForm = document.getElementById("serviceForm");
const year = document.getElementById("year");

let currentLang = localStorage.getItem("siteLang") || "en";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("siteLang", lang);

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  langToggle.textContent = lang === "en" ? "العربية" : "English";
}

langToggle.addEventListener("click", () => {
  setLanguage(currentLang === "en" ? "ar" : "en");
});

menuBtn.addEventListener("click", () => {
  navMenu.classList.toggle("active");
});

document.querySelectorAll(".nav-menu a").forEach((link) => {
  link.addEventListener("click", () => {
    navMenu.classList.remove("active");
  });
});

serviceForm.addEventListener("submit", function (event) {
  event.preventDefault();

  const formData = new FormData(serviceForm);

  const name = formData.get("name");
  const phone = formData.get("phone");
  const email = formData.get("email") || "Not provided";
  const service = formData.get("service");
  const property = formData.get("property");
  const location = formData.get("location");
  const date = formData.get("date");
  const message = formData.get("message");

  const whatsappNumber = "966554626794";

  const whatsappMessage =
    `New Service Request - Almanzil Service%0A%0A` +
    `Full Name: ${encodeURIComponent(name)}%0A` +
    `Phone: ${encodeURIComponent(phone)}%0A` +
    `Email: ${encodeURIComponent(email)}%0A` +
    `Service Required: ${encodeURIComponent(service)}%0A` +
    `Property Type: ${encodeURIComponent(property)}%0A` +
    `Location: ${encodeURIComponent(location)}%0A` +
    `Preferred Date: ${encodeURIComponent(date)}%0A` +
    `Message: ${encodeURIComponent(message)}`;

  window.open(`https://wa.me/${whatsappNumber}?text=${whatsappMessage}`, "_blank");
});

year.textContent = new Date().getFullYear();

setLanguage(currentLang);
